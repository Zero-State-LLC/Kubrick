def _shadow(module: str, directory: Path) -> dict[str, str]:
    shadow = directory / f"{module}.py"
    shadow.write_text("raise ImportError('simulated missing module')\n", encoding="utf-8")
    env = os.environ.copy()
    previous = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = str(directory) + (os.pathsep + previous if previous else "")
    env["KUBRICK_DIAGNOSTICS"] = "json"
    return env


def _routed(module: str, args: list[str]) -> subprocess.CompletedProcess[str]:
    with tempfile.TemporaryDirectory() as directory:
        env = _shadow(module, Path(directory))
        return subprocess.run(
            [PY, str(SCRIPTS / "kubrick.py"), *args],
            cwd=ROOT, text=True, capture_output=True, check=False, env=env,
        )


def _diagnostic(proc: subprocess.CompletedProcess[str]) -> dict[str, object]:
    text = (proc.stderr or proc.stdout).strip().splitlines()[-1]
    loaded = json.loads(text)
    assert isinstance(loaded, dict)
    return loaded


def test_b7_missing_runtime_dependency_is_exit_4() -> None:
    plan = "examples/myslef-minder/storyboard-plan.yaml"
    retime = _routed(
        "yaml",
        ["video", "--action", "retime", "--provider", "keyframe", "--input", plan],
    )
    impact = _routed(
        "yaml",
        [
            "storyboard", "--action", "impact",
            "--storyboard", plan,
            "--takes", "examples/myslef-minder/takes.yaml",
            "--retake", "04",
        ],
    )
    adapt = _routed(
        "jsonschema",
        [
            "video",
            "--action",
            "adapt",
            "--provider",
            "keyframe",
            "--input",
            plan,
            "--output",
            "/tmp/p1-b7-adapt.yaml",
        ],
    )
    for proc, package in ((retime, "PyYAML"), (impact, "PyYAML"), (adapt, "jsonschema")):
        assert proc.returncode == 4, proc.stderr
        payload = _diagnostic(proc)
        assert payload["code"] == "DEPENDENCY_MISSING"
        assert payload["status"] == "DEPENDENCY_UNAVAILABLE"
        assert payload["exit_code"] == 4
        context = payload["context"]
        assert isinstance(context, dict)
        assert context["package"] == package
        assert "requirements.txt" in str(context["install"])


